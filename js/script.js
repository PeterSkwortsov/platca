const sliderState = {};

function slideNext(event, key) {
    event.stopPropagation();
    const state = sliderState[key] || { current: 0, total: 4 };
    state.current = (state.current + 1) % state.total;
    sliderState[key] = state;
    updateSlider(key);
}

function slidePrev(event, key) {
    event.stopPropagation();
    const state = sliderState[key] || { current: 0, total: 4 };
    state.current = (state.current - 1 + state.total) % state.total;
    sliderState[key] = state;
    updateSlider(key);
}

function slideTo(event, key, index) {
    event.stopPropagation();
    const state = sliderState[key] || { current: 0, total: 4 };
    state.current = index;
    sliderState[key] = state;
    updateSlider(key);
}

function updateSlider(key) {
    const state = sliderState[key] || { current: 0, total: 4 };
    const slider = document.querySelector(`[data-slider="${key}"]`);
    if (!slider) return;

    const track = slider.querySelector('.slider-track');
    const dots = slider.querySelectorAll('.slider-dot');
    const counter = slider.querySelector('.slider-counter .current');

    track.style.transform = `translateX(-${state.current * 100}%)`;
    dots.forEach((dot, i) => dot.classList.toggle('active', i === state.current));
    if (counter) counter.textContent = state.current + 1;
}

