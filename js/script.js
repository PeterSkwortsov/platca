function initVideoOnScroll() {
    const videoHero = document.getElementById('videoHero');
    const video = document.getElementById('heroVideo');
    const quote = document.getElementById('quoteOverlay');

    if (!videoHero || !video) return;

    const isMobile = window.innerWidth <= 600;
    const quoteDelay = isMobile ? 10000 : 9000;

    let hasStarted = false;

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting && !hasStarted) {
                hasStarted = true;
                video.currentTime = 0;
                video.play().catch(error => {
                    console.log('Автоплей заблокирован:', error);
                    document.body.addEventListener('click', () => video.play(), { once: true });
                });

                setTimeout(() => {
                    if (quote) quote.classList.add('visible');
                }, quoteDelay);
            }
        });
    }, {
        threshold: 0.4
    });

    observer.observe(videoHero);
}

