let savedScrollPosition = 0;

function showMain() {
    // Показываем hero и видео-блок обратно
    document.querySelector('.hero').classList.remove('hidden');
    document.getElementById('videoHero').classList.remove('hidden');

    document.getElementById('main-page').style.display = 'block';
    document.querySelectorAll('.direction-page').forEach(p => p.classList.remove('active'));

    requestAnimationFrame(() => {
        requestAnimationFrame(() => {
            window.scrollTo(0, savedScrollPosition);
        });
    });
}

function showDirection(type) {
    savedScrollPosition = window.pageYOffset || document.documentElement.scrollTop;

    // Скрываем hero и видео-блок
    document.querySelector('.hero').classList.add('hidden');
    document.getElementById('videoHero').classList.add('hidden');

    document.getElementById('main-page').style.display = 'none';
    document.querySelectorAll('.direction-page').forEach(p => p.classList.remove('active'));

    const target = document.getElementById('direction-' + type);
    if (target) target.classList.add('active');
    window.scrollTo(0, 0);
}

